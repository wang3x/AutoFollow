using System.Numerics;
using AutoFollow.Movement;

var checks = 0;
void Check(bool condition, string name)
{
    if (!condition) throw new Exception(name);
    checks++;
}
var requests = new PathRequestGuard();
var first = requests.Next();
var second = requests.Next();
Check(!requests.IsCurrent(first), "Older path cannot replace newer path");
Check(requests.IsCurrent(second), "Newest request accepted");
requests.Next(); // Stop, target switch, loading and disposal all invalidate before stopping.
Check(!requests.IsCurrent(second), "Late completion after stop rejected");
Check(!PathRequestGuard.CompletePath(null, Vector3.One), "Null path rejected");
Check(!PathRequestGuard.CompletePath([], Vector3.One), "Empty path rejected");
Check(!PathRequestGuard.CompletePath([Vector3.Zero], new Vector3(10)), "Partial path rejected");
Check(!PathRequestGuard.CompletePath([new(float.NaN), Vector3.One], Vector3.One), "Invalid waypoint rejected");
Check(PathRequestGuard.CompletePath([Vector3.Zero, Vector3.One], Vector3.One), "Complete path accepted");
var self = new AutoFollow.Models.PartyCandidate(0, 1, true, true, false);
var tank = new AutoFollow.Models.PartyCandidate(1, 2, true, true, true);
var dps = new AutoFollow.Models.PartyCandidate(2, 3, true, true, false);
Check(AutoFollow.Models.PartySelection.Select([self, tank, dps], 1, 0) == 2, "Single tank wins");
Check(AutoFollow.Models.PartySelection.Select([self, tank, dps with { Tank = true }], 1, 2) == 3, "Multiple tanks follow leader");
Check(AutoFollow.Models.PartySelection.Select([self, tank with { Alive = false }, dps], 1, 0) == 3, "Dead tank excluded");
Check(AutoFollow.Models.PartySelection.Select([self, tank with { Online = false }, dps], 1, 0) == 3, "Offline tank excluded");
Check(AutoFollow.Models.PartySelection.Select([self with { Tank = true }, dps], 1, 0) == 3, "Self tank falls back");
Check(AutoFollow.Models.PartySelection.Select([self, tank, dps with { Tank = true }], 1, 0) == 2, "Self leader falls back");
Check(AutoFollow.Models.PartySelection.Select([self], 1, 0) == null, "Never follow self");
Check(AutoFollow.Models.PartySelection.Select([], 1, 0) == null, "Empty party waits");
Check(AutoFollow.Models.PartySelection.Select([self, dps], 1, 0) == 3, "No tanks falls back");
var now = new DateTime(2026, 10, 26, 0, 0, 0, DateTimeKind.Utc);
var history = new TargetHistory();
Check(history.Observe(now, Vector3.Zero), "First sample accepted");
Check(history.Direction(now) == null, "Single sample cannot authorize push");
Check(history.Observe(now.AddSeconds(0.5), Vector3.UnitX), "Walking sample accepted");
Check(history.Direction(now.AddSeconds(0.5)) == Vector3.UnitX, "Direction from recent movement");
Check(!history.Observe(now.AddSeconds(0.6), new Vector3(100, 0, 0)), "Same-map teleport detected");
Check(history.Last == Vector3.UnitX, "Teleport destination cannot replace source");
Check(history.Direction(now.AddSeconds(4)) == null, "Old direction expires");
Check(!history.Observe(now, new Vector3(float.NaN)), "NaN sample rejected");
history.Clear();
Check(history.Last == null, "Target changes clear history");

var recovery = new TransitionRecovery();
RecoveryStep Begin(Vector3? source, Vector3? direction = null, AutoFollow.Models.TransitionProfile? profile = null, bool allow = true)
    => recovery.Begin(now, Vector3.Zero, source, direction, profile, allow);
Check(Begin(new Vector3(31, 0, 0)).Action == RecoveryAction.Stop, "Distant entrance rejected");
Check(Begin(null).Action == RecoveryAction.Stop, "Missing entrance rejected");
Check(Begin(Vector3.Zero, allow: false).Action == RecoveryAction.Stop, "Disabled speculation stops");
Check(Begin(new Vector3(10, 0, 0)).Action == RecoveryAction.Navigate, "Approach reliable source");
Check(recovery.Tick(now.AddSeconds(0.1), Vector3.Zero, PathStatus.Pending, null).Action == RecoveryAction.None, "Pending is not blocked");
Check(recovery.Tick(now.AddSeconds(10), Vector3.Zero, PathStatus.Pending, null).Action == RecoveryAction.Stop, "Approach times out");
Check(recovery.Phase == RecoveryPhase.Paused, "Timeout pauses");
Check(recovery.Tick(now.AddSeconds(11), Vector3.Zero, PathStatus.Stopped, null).Action == RecoveryAction.None, "No repeated speculative approach");
Begin(new Vector3(10, 0, 0), Vector3.UnitX);
Check(recovery.Tick(now.AddSeconds(0.1), Vector3.Zero, PathStatus.Failed, null).Action == RecoveryAction.Stop, "Path failure cannot authorize push");
Begin(new Vector3(10, 0, 0), Vector3.UnitX);
recovery.Tick(now.AddSeconds(0.1), Vector3.Zero, PathStatus.Moving, null);
Check(recovery.Tick(now.AddSeconds(1.1), Vector3.Zero, PathStatus.Moving, null).Action == RecoveryAction.Stop, "Stuck approach stops");
Begin(Vector3.Zero);
Check(recovery.Tick(now.AddSeconds(0.1), Vector3.Zero, PathStatus.Pending, null).Action == RecoveryAction.Stop, "Unknown direction waits in place");
Check(recovery.Phase == RecoveryPhase.Waiting, "Waiting mode entered");
Check(recovery.Tick(now.AddSeconds(10.2), Vector3.Zero, PathStatus.Stopped, null).Action == RecoveryAction.Stop, "Waiting times out");
Begin(Vector3.Zero, Vector3.UnitX);
var push = recovery.Tick(now.AddSeconds(0.1), Vector3.Zero, PathStatus.Pending, null);
Check(push.Action == RecoveryAction.Direct && push.Destination == new Vector3(5, 0, 0), "Push bounded to five yalms");
Check(recovery.Tick(now.AddSeconds(2.1), new Vector3(2, 0, 0), PathStatus.Moving, null).Action == RecoveryAction.Stop, "Push bounded to two seconds");
Begin(Vector3.Zero, Vector3.UnitX);
recovery.Tick(now.AddSeconds(0.1), Vector3.Zero, PathStatus.Pending, null);
Check(recovery.Tick(now.AddSeconds(0.5), new Vector3(5, 0, 0), PathStatus.Arrived, null).Action == RecoveryAction.Stop, "Push distance cap");
Begin(Vector3.Zero, Vector3.UnitX);
recovery.Tick(now.AddSeconds(0.1), Vector3.Zero, PathStatus.Pending, null);
Check(recovery.Tick(now.AddSeconds(0.5), new Vector3(100, 0, 0), PathStatus.Moving, null).Action == RecoveryAction.Stop, "Player teleport stops direct movement");
recovery.Hold(now);
Check(recovery.Phase == RecoveryPhase.Waiting, "Loading suspends recovery");
Check(recovery.Profile == null, "Loading invalidates interaction authorization");
var visible = new Vector3(20, 0, 0);
Check(recovery.Tick(now.AddSeconds(1), Vector3.Zero, PathStatus.Stopped, visible).Action == RecoveryAction.Probe, "Reappearance probes without moving");
Check(recovery.Tick(now.AddSeconds(1.1), Vector3.Zero, PathStatus.Pending, visible).Action == RecoveryAction.None, "No move while probing");
Check(recovery.Tick(now.AddSeconds(1.2), Vector3.Zero, PathStatus.Reachable, visible).Action == RecoveryAction.Resume, "Only complete reachable path resumes");
Check(!recovery.Active, "Successful recovery clears episode");
recovery.Fail("test");
recovery.Tick(now.AddSeconds(2), Vector3.Zero, PathStatus.Stopped, visible);
Check(recovery.Tick(now.AddSeconds(2.1), Vector3.Zero, PathStatus.Reachable, visible + new Vector3(100, 0, 0)).Action == RecoveryAction.Stop, "Stale probe after target jump rejected");
recovery.Clear();
Check(recovery.Tick(now.AddSeconds(3), Vector3.Zero, PathStatus.Reachable, visible).Action == RecoveryAction.None, "Cleared manual stop cannot resume");

var profile = new AutoFollow.Models.TransitionProfile { EntryId = "test", TerritoryId = 1, Source = Vector3.Zero, Kind = AutoFollow.Models.TransitionKind.Wait };
Check(profile.Matches(1, Vector3.Zero), "Verified entrance matches territory and position");
Check(!profile.Matches(2, Vector3.Zero), "Other territory rejected");
Check(!profile.Matches(1, new Vector3(10)), "Other entrance rejected");
Begin(Vector3.Zero, Vector3.UnitX, profile);
Check(recovery.Tick(now.AddSeconds(0.1), Vector3.Zero, PathStatus.Pending, null).Action == RecoveryAction.Stop && recovery.Phase == RecoveryPhase.Waiting, "Wait profile never pushes");
profile.Kind = AutoFollow.Models.TransitionKind.Interact;
Check(!profile.Matches(1, Vector3.Zero), "Interaction requires explicit object ID");
profile.ObjectDataId = 123;
Check(profile.Matches(1, Vector3.Zero), "Explicit interaction profile accepted");
Begin(Vector3.Zero, Vector3.UnitX, profile);
Check(recovery.Tick(now.AddSeconds(0.1), Vector3.Zero, PathStatus.Pending, null).Action == RecoveryAction.Interact, "Known entrance issues one interaction");
Check(recovery.Tick(now.AddSeconds(0.2), Vector3.Zero, PathStatus.Stopped, null).Action == RecoveryAction.None, "Interaction never repeats");
profile.Kind = AutoFollow.Models.TransitionKind.Walk;
Check(!profile.Matches(1, Vector3.Zero), "Known walk requires explicit endpoint");
profile.WalkDestination = new Vector3(6, 0, 0);
Check(!profile.Matches(1, Vector3.Zero), "Oversized profile push rejected");
profile.WalkDestination = new Vector3(4, 0, 0);
Check(profile.Matches(1, Vector3.Zero), "Bounded walk profile accepted");
Begin(Vector3.Zero, null, profile);
Check(recovery.Tick(now.AddSeconds(0.1), Vector3.Zero, PathStatus.Pending, null).Destination == profile.WalkDestination, "Known endpoint used without guessed direction");
Check(AutoFollow.Models.PartySelection.Select([self, dps with { Tank = true }], 1, 0) == 3, "Leaving member removed from selection");
Check(AutoFollow.Models.PartySelection.Select([self, tank, dps with { Tank = true }], 1, 1) == 2, "Leader changes update priority");
var frame = new AutoFollow.Tests.FrameworkFake();
var objects = new AutoFollow.Tests.ObjectsFake();
var party = new AutoFollow.Tests.PartyFake();
var dtr = new AutoFollow.Tests.DtrFake();
var engine = new AutoFollow.FollowEngine();
var clock = now;
var memberSelf = new Dalamud.Plugin.Services.FakeMember { ContentId = 1, EntityId = 1 };
var memberTank = new Dalamud.Plugin.Services.FakeMember { ContentId = 2, EntityId = 2 };
memberTank.ClassJob.Value.Role = 1;
party.AddRange([memberSelf, memberTank]);
var controller = new AutoFollow.PartyFollowController(party, objects, frame, dtr, engine, () => clock);
void TickController() { clock = clock.AddSeconds(1); frame.Tick(); }
TickController();
Check(!controller.Enabled && engine.Selections == 0, "DTR starts OFF");
dtr.Click(); TickController();
Check(engine.TargetContentId == 2 && engine.Selections == 1, "ON selects tank");
var resetCount = engine.Resets;
TickController();
Check(engine.TargetContentId == 2 && engine.Selections == 1 && engine.Resets == resetCount, "Stable target never reset or reselected");
memberTank.GameObject = null; TickController();
Check(engine.TargetContentId == 2 && engine.Selections == 1, "Target absence retains ContentId");
memberTank.GameObject = new();
engine.Pause("manual"); TickController();
Check(engine.Selections == 1, "Manual pause prevents automatic restart");
engine.ChangeState(AutoFollow.Models.FollowState.Following); TickController();
Check(engine.Selections == 1, "Explicit resume preserves selection");
engine.ChangeState(AutoFollow.Models.FollowState.EmergencyStopped); TickController();
Check(engine.Selections == 1, "F8 prevents automatic restart");
dtr.Click();
Check(!controller.Enabled && engine.State == AutoFollow.Models.FollowState.Paused, "OFF stops movement intent");
dtr.Click(); TickController();
Check(engine.Selections == 2, "Explicit OFF to ON rearms");
AutoFollow.PartyStatusReader.States[2] = false; TickController();
Check(engine.TargetContentId == null, "Disconnected target removed even if visible");
AutoFollow.PartyStatusReader.States[2] = true; TickController();
Check(engine.TargetContentId == 2, "Online target can be reacquired");
engine.SetTarget("ManualPlayer"); TickController();
Check(!controller.Enabled, "Manual target exits automatic selection");
dtr.Click(); TickController();
controller.Disable(); engine.ResetToIdle();
var selectedBeforeDuty = engine.Selections; TickController();
Check(engine.Selections == selectedBeforeDuty, "Duty completion cannot rearm auto selection");
dtr.Click(); memberSelf.EntityId = 999; TickController();
Check(engine.TargetContentId == null, "Unknown self identity cannot select self");
controller.Dispose();
Check(dtr.Removed, "Dispose removes DTR entry");
Console.WriteLine($"PASS: {checks} checks");
